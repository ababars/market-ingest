#!/usr/bin/env bash
# Stage 1+, runs on the LAPTOP but does all its work on the SERVER.
#
# Ships this directory to /root/vps-provision on the VPS (as a tar stream, so a
# bare server with no rsync is fine) and runs remote/run.sh there. The whole
# transcript is teed into ./logs/ locally and /var/log/vps-provision/ remotely.
#
#   ./provision.sh                       all steps
#   ./provision.sh 50-clickhouse         one step
#   ./provision.sh 30-tools 60-netdata   several

set -Eeuo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# On the laptop /var/lib is not ours to write to.
export STATE_DIR="${STATE_DIR:-${XDG_STATE_HOME:-$HOME/.local/state}/vps-toolkit}"
# shellcheck source=lib/common.sh
source "$HERE/lib/common.sh"

[[ -f "$HERE/.env" ]] || die "no $HERE/.env - copy .env.example to .env and fill it in"
set -a; source "$HERE/.env"; set +a

: "${VPS_HOST:?set VPS_HOST in .env}"
: "${VPS_ALIAS:?set VPS_ALIAS in .env}"
SSH_PORT="${SSH_PORT:-22}"
SSH_KEY="${SSH_KEY:-$HOME/.ssh/id_ed25519}"; SSH_KEY="${SSH_KEY/#\~/$HOME}"

STEPS_ARG="${*:-${STEPS:-}}"

REMOTE_DIR=/root/vps-provision
SSH=(ssh -o ConnectTimeout=15 -o BatchMode=yes -i "$SSH_KEY" -p "$SSH_PORT" "root@$VPS_HOST")

section "Connectivity"
"${SSH[@]}" true 2>/dev/null \
  || die "cannot reach root@$VPS_HOST:$SSH_PORT by key - run ./bootstrap.sh first"
ok "root@$VPS_HOST reachable by key"

# ------------------------------------------------------- server-side env file
# Deliberately excludes VPS_ROOT_PASS and the local SSH_KEY path: the server has
# no business knowing either.
REMOTE_ENV="$(mktemp)"; trap 'rm -f "$REMOTE_ENV"' EXIT
{
  echo "# generated by provision.sh on $(date -u +%FT%TZ) - do not edit by hand"
  for v in VPS_HOST VPS_ALIAS VPS_USER VPS_TZ SSH_PORT HARDEN_ROOT_LOGIN \
           SWAP_SIZE INSTALL_DOCKER GIT_USER_NAME GIT_USER_EMAIL \
           CH_DB CH_PASSWORD CH_MEM_RATIO CH_MAX_MEMORY \
           NETDATA_CLAIM_TOKEN NETDATA_CLAIM_ROOMS \
           NETDATA_TG_BOT_TOKEN NETDATA_TG_CHAT_ID; do
    printf '%s=%q\n' "$v" "${!v-}"
  done
} > "$REMOTE_ENV"

section "Uploading toolkit"
"${SSH[@]}" "install -d -m 0700 $REMOTE_DIR"
tar -C "$HERE" -cz --exclude='.env' --exclude='logs' --exclude='.git' \
    lib remote dotfiles \
  | "${SSH[@]}" "tar -C $REMOTE_DIR -xz"
# shipped separately so it never lands in the tarball or in git
cat "$REMOTE_ENV" | "${SSH[@]}" "cat > $REMOTE_DIR/env && chmod 600 $REMOTE_DIR/env"
"${SSH[@]}" "chmod +x $REMOTE_DIR/remote/*.sh"
ok "toolkit is at $REMOTE_DIR"

section "Running remote provisioning"
mkdir -p "$HERE/logs"
LOG="$HERE/logs/provision-$(date -u +%Y%m%d-%H%M%S).log"

set +e
ssh -tt -o ConnectTimeout=15 -i "$SSH_KEY" -p "$SSH_PORT" "root@$VPS_HOST" \
    "bash $REMOTE_DIR/remote/run.sh $STEPS_ARG" 2>&1 | tee "$LOG"
rc=${PIPESTATUS[0]}
set -e

echo
if (( rc == 0 )); then
  ok "provisioning finished. Local log: ${LOG#"$HERE"/}"
else
  die "provisioning failed (exit $rc). Local log: ${LOG#"$HERE"/}"
fi
